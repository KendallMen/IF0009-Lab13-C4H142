CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    nombre_completo VARCHAR(160) NOT NULL,
    rol VARCHAR(30) NOT NULL
);

CREATE TABLE medicamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nombre VARCHAR(160) NOT NULL,
    stock INT NOT NULL,
    precio_unitario DECIMAL(12,2) NOT NULL
);

CREATE TABLE recetas_medicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_receta VARCHAR(50) NOT NULL UNIQUE,
    paciente_nombre VARCHAR(160) NOT NULL,
    medico_id BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL,
    fecha_emision TIMESTAMP NOT NULL,
    CONSTRAINT fk_receta_medico FOREIGN KEY (medico_id) REFERENCES usuarios(id)
);

CREATE TABLE detalles_receta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receta_id BIGINT NOT NULL,
    medicamento_id BIGINT NOT NULL,
    cantidad INT NOT NULL,
    dosis_indicada VARCHAR(255) NOT NULL,
    CONSTRAINT fk_detalle_receta FOREIGN KEY (receta_id) REFERENCES recetas_medicas(id),
    CONSTRAINT fk_detalle_medicamento FOREIGN KEY (medicamento_id) REFERENCES medicamentos(id)
);
